import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const specPath = resolve(root, process.env.REALTIME_OPENAPI_SPEC ?? "openapi/refract-api.yaml");
const outPath = resolve(root, "src/lib/realtime/generated/schemas.ts");
const indexPath = resolve(root, "src/lib/realtime/generated/index.ts");
const check = process.argv.includes("--check");
const spec = readFileSync(specPath, "utf8");
if (
  !/^openapi:\s*3\./m.test(spec) ||
  !/^components:\s*$/m.test(spec) ||
  !/^  schemas:\s*$/m.test(spec)
)
  throw new Error("Invalid OpenAPI document: expected OpenAPI 3 and components.schemas");
const wanted = ["OracleReading", "ClaimRecord", "PoolStats", "RealtimeEnvelope"];
const schemas = {};
for (const name of wanted) {
  const start = spec.indexOf(`    ${name}:`);
  if (start < 0) throw new Error(`Required realtime schema '${name}' is missing from ${specPath}`);
  const boundary = spec.slice(start + 5).search(/\n    [A-Z][A-Za-z0-9]*:/);
  const next = boundary < 0 ? -1 : start + 5 + boundary;
  const block = spec.slice(start, next < 0 ? undefined : next);
  const requiredLine = block.match(/^      required:\s*\[([^\]]*)\]/m)?.[1];
  if (!requiredLine) throw new Error(`Schema '${name}' has no required field declaration`);
  const required = new Set(
    requiredLine
      .split(",")
      .map((v) => v.trim())
      .filter(Boolean)
  );
  const propsStart = block.indexOf("      properties:");
  if (propsStart < 0) throw new Error(`Schema '${name}' has no properties`);
  const propsText = block.slice(propsStart + 7);
  const props = [];
  const lines = propsText.split("\n");
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    const field = line.match(/^        ([A-Za-z][\w]*):(?:\s*\{\s*(.*?)\s*\})?\s*$/);
    if (!field) continue;
    let descriptor = field[2] ?? "";
    if (!descriptor) {
      const nested = lines.slice(i + 1, i + 5).join(" ");
      descriptor = nested;
    }
    const type = descriptor.match(
      /(?:^|[,\s])type:\s*(string|number|integer|boolean|object|array)/
    )?.[1];
    const enumBody = descriptor.match(/enum:\s*\[([^\]]*)\]/)?.[1];
    const nullable = /nullable:\s*true/.test(descriptor);
    if (!type && !enumBody) throw new Error(`Unsupported or malformed field '${name}.${field[1]}'`);
    let tsType =
      type === "integer" || type === "number"
        ? "number"
        : type === "boolean"
          ? "boolean"
          : type === "object"
            ? "Record<string, unknown>"
            : type === "array"
              ? "unknown[]"
              : "string";
    let zod =
      type === "number" || type === "integer"
        ? "z.number()"
        : type === "boolean"
          ? "z.boolean()"
          : type === "object"
            ? "z.record(z.string(), z.unknown())"
            : "z.string()";
    if (enumBody) {
      const vals = enumBody
        .split(",")
        .map((v) => v.trim())
        .filter(Boolean);
      tsType = vals
        .map((v) => v.replace(/^['"]|['"]$/g, ""))
        .map((v) => JSON.stringify(v))
        .join(" | ");
      zod = `z.enum([${vals.map((v) => JSON.stringify(v.replace(/^['"]|['"]$/g, ""))).join(", ")}])`;
    }
    if (nullable) {
      tsType += " | null";
      zod += ".nullable()";
    }
    const optional = !required.has(field[1]);
    props.push({ key: field[1], tsType, zod: optional ? `${zod}.optional()` : zod, optional });
  }
  props.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  for (const field of required)
    if (!props.some((p) => p.key === field))
      throw new Error(`Required field '${name}.${field}' is missing from properties`);
  schemas[name] = props;
}
const lines = [
  "// Generated by scripts/gen-realtime-types.mjs. Do not edit.",
  'import { z } from "zod";',
  "",
];
for (const [name, props] of Object.entries(schemas)) {
  lines.push(`export interface ${name} {`);
  for (const p of props) lines.push(`  ${p.key}${p.optional ? "?" : ""}: ${p.tsType};`);
  lines.push("}", `export const ${name}Schema = z.object({`);
  for (const p of props) lines.push(`  ${p.key}: ${p.zod},`);
  lines.push("});", "");
}
const output = `${lines.join("\n").trimEnd()}\n`;
const indexOutput = `// Generated by scripts/gen-realtime-types.mjs. Do not edit.\nexport { ${wanted.map((n) => `${n}Schema`).join(", ")} } from "./schemas";\nexport type { ${wanted.join(", ")} } from "./schemas";\n`;
if (check) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    /* drift */
  }
  let currentIndex = "";
  try {
    currentIndex = readFileSync(indexPath, "utf8");
  } catch {
    /* drift */
  }
  if (current !== output || currentIndex !== indexOutput) {
    console.error("Realtime generated files are stale. Run npm run gen:realtime-types.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outPath, output);
  writeFileSync(indexPath, indexOutput);
}
